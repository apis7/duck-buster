// Writes src/quiz/media.generated.ts from whatever is in assets/quiz/{img,audio}
// plus credits.json. Re-run after adding or replacing quiz media.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const list = (dir) => (existsSync(join(root, dir)) ? readdirSync(join(root, dir)) : []);
const strip = (f) => f.replace(/\.[^.]+$/, '');

const images = list('assets/quiz/img').filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort();
const sounds = list('assets/quiz/audio').filter((f) => /\.(mp3|m4a|aac|wav|ogg)$/i.test(f)).sort();
const creditsPath = join(root, 'assets/quiz/credits.json');
const credits = existsSync(creditsPath) ? JSON.parse(readFileSync(creditsPath, 'utf8')) : [];

const credit = (code, kind) => {
  const c = credits.find((x) => x.code === code && x.kind === kind);
  return c ? `${c.author || 'Unknown'} · ${c.license}` : '';
};

const lines = [
  '// Generated by scripts/gen-quiz-media.mjs. Do not edit by hand.',
  '',
  'export const QUIZ_IMAGES: Record<string, { src: number; credit: string }> = {',
  ...images.map((f) => `  ${JSON.stringify(strip(f))}: { src: require('../../assets/quiz/img/${f}'), credit: ${JSON.stringify(credit(strip(f), 'image'))} },`),
  '};',
  '',
  'export const QUIZ_SOUNDS: Record<string, { src: number; credit: string }> = {',
  ...sounds.map((f) => `  ${JSON.stringify(strip(f))}: { src: require('../../assets/quiz/audio/${f}'), credit: ${JSON.stringify(credit(strip(f), 'audio'))} },`),
  '};',
  '',
];
mkdirSync(join(root, 'src/quiz'), { recursive: true });
writeFileSync(join(root, 'src/quiz/media.generated.ts'), lines.join('\n'));
console.log(`quiz media: ${images.length} images, ${sounds.length} sounds`);
